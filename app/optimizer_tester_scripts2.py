def save_results_to_excel(
    optimizer_name,
    solve_time,
    ingredient_json,
    macros_json,
    file_name = r"your_file.xlsx"
):
    """
    Saves optimizer results into Excel.

    Parameters
    ----------
    optimizer_name : str
    solve_time : float
    ingredient_json : list[dict]
    macros_json : dict
    file_name : str
    """

    ingredient_rows = []

    for ing in ingredient_json:
        ingredient_rows.append({
            "optimizer": optimizer_name,
            "time_seconds": round(solve_time, 6),
            "name": ing.get("name"),
            "grams": ing.get("grams"),
        })

    macro_row = {
        "optimizer": optimizer_name,
        "time_seconds": round(solve_time, 6),
        **macros_json
    }

    df_ing = pd.DataFrame(ingredient_rows)
    df_mac = pd.DataFrame([macro_row])

    # If file does not exist → create it
    if not os.path.exists(file_name):

        with pd.ExcelWriter(file_name, engine="openpyxl") as writer:
            df_ing.to_excel(writer, sheet_name="ingredients", index=False)
            df_mac.to_excel(writer, sheet_name="macros", index=False)

    else:

        with pd.ExcelWriter(file_name, engine="openpyxl", mode="a", if_sheet_exists="overlay") as writer:

            try:
                existing_ing = pd.read_excel(file_name, sheet_name="ingredients")
                df_ing = pd.concat([existing_ing, df_ing], ignore_index=True)
            except:
                pass

            try:
                existing_mac = pd.read_excel(file_name, sheet_name="macros")
                df_mac = pd.concat([existing_mac, df_mac], ignore_index=True)
            except:
                pass

            df_ing.to_excel(writer, sheet_name="ingredients", index=False)
            df_mac.to_excel(writer, sheet_name="macros", index=False)


